    /**
     * Valida los datos capturados y, si son correctos, guarda la mesa en el
     * manager y cierra la ventana.
     */
    private void guardar() {
        int cantidad;
        int estado;
        try {
            cantidad = valor(spnCantidad);
        } catch (ParseException e) {
            advertir(NUMERO_INVALIDO, spnCantidad);
            return;
        }
        try {
            estado = valor(spnEstado);
        } catch (ParseException e) {
            advertir(NUMERO_INVALIDO, spnEstado);
            return;
        }

        Mesa mesa = new Mesa(cantidad, estado);
        try {
            if (original == null) {
                Mesa creada = manager.crearMesa(mesa);
                informar("Mesa creada con id: " + creada.getId());
            } else {
                mesa.setId(original.getId());
                if (!manager.actualizarMesa(mesa)) {
                    advertir("No se encontró la mesa a actualizar.", spnCantidad);
                    return;
                }
                informar("Mesa actualizada correctamente.");
            }
        } catch (IllegalArgumentException e) {
            advertir(e.getMessage(), spnCantidad);
            return;
        }
        if (alGuardar != null) {
            alGuardar.run();
        }
        dispose();
    }

    /**
     * Confirma lo que el usuario haya escrito en el spinner y lo devuelve.
     *
     * @param spinner spinner numérico
     * @return el valor entero del spinner
     * @throws ParseException si el texto no es un número válido o está fuera de rango
     */
    private static int valor(JSpinner spinner) throws ParseException {
        spinner.commitEdit();
        return ((Number) spinner.getValue()).intValue();
    }

    /**
     * Asigna un valor al spinner ajustándolo al rango de su modelo.
     *
     * @param spinner spinner numérico
     * @param valor   valor deseado
     */
    private static void fijar(JSpinner spinner, int valor) {
        SpinnerNumberModel modelo = (SpinnerNumberModel) spinner.getModel();
        int minimo = ((Number) modelo.getMinimum()).intValue();
        int maximo = ((Number) modelo.getMaximum()).intValue();
        spinner.setValue(Math.max(minimo, Math.min(maximo, valor)));
    }

    /**
     * Muestra una advertencia y devuelve el foco al componente indicado.
     *
     * @param mensaje    texto a mostrar
     * @param componente componente que recibe el foco
     */
    private void advertir(String mensaje, java.awt.Component componente) {
        JOptionPane.showMessageDialog(this, mensaje, TITULO_VALIDACION,
                JOptionPane.WARNING_MESSAGE);
        componente.requestFocusInWindow();
    }

    /**
     * Muestra un mensaje informativo.
     *
     * @param mensaje texto a mostrar
     */
    private void informar(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, TITULO_RESULTADO,
                JOptionPane.INFORMATION_MESSAGE);
    }

