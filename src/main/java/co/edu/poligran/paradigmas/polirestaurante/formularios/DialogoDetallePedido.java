    /**
     * Valida los datos capturados y, si son correctos, guarda el detalle en el
     * manager y cierra la ventana.
     * <p>
     * Al crear se exige que el pedido exista. Al editar se conserva el pedido
     * original del detalle.
     * </p>
     */
    private void guardar() {
        int idPedido;
        double precio;
        int cantidad;
        try {
            idPedido = valorEntero(spnIdPedido);
        } catch (ParseException e) {
            advertir(NUMERO_INVALIDO, spnIdPedido);
            return;
        }
        try {
            precio = valorDecimal(spnPrecio);
        } catch (ParseException e) {
            advertir(NUMERO_INVALIDO, spnPrecio);
            return;
        }
        try {
            cantidad = valorEntero(spnCantidad);
        } catch (ParseException e) {
            advertir(NUMERO_INVALIDO, spnCantidad);
            return;
        }

        if (original == null && erik != null && erik.buscarPedidoPorId(idPedido) == null) {
            advertir(PEDIDO_NO_EXISTE, spnIdPedido);
            return;
        }

        try {
            if (original == null) {
                DetallePedido creado = angie.crearDetalle(new DetallePedido(idPedido, precio, cantidad));
                informar("Detalle creado con id: " + creado.getIdDetalle()
                        + "\nSubtotal: " + creado.getSubtotal());
            } else {
                DetallePedido datos = new DetallePedido(original.getIdDetalle(),
                        original.getIdPedido(), precio, cantidad);
                if (!angie.actualizarDetalle(datos)) {
                    advertir("No se encontró el detalle a actualizar.", spnPrecio);
                    return;
                }
                informar("Detalle actualizado correctamente.\nSubtotal: " + datos.getSubtotal());
            }
        } catch (IllegalArgumentException e) {
            advertir(e.getMessage(), spnIdPedido);
            return;
        }
        if (alGuardar != null) {
            alGuardar.run();
        }
        dispose();
    }

    /**
     * Confirma lo que el usuario haya escrito en el spinner y lo devuelve como entero.
     *
     * @param spinner spinner numérico
     * @return el valor entero del spinner
     * @throws ParseException si el texto no es un número válido o está fuera de rango
     */
    private static int valorEntero(JSpinner spinner) throws ParseException {
        spinner.commitEdit();
        return ((Number) spinner.getValue()).intValue();
    }

    /**
     * Confirma lo que el usuario haya escrito en el spinner y lo devuelve como decimal.
     *
     * @param spinner spinner numérico
     * @return el valor decimal del spinner
     * @throws ParseException si el texto no es un número válido o está fuera de rango
     */
    private static double valorDecimal(JSpinner spinner) throws ParseException {
        spinner.commitEdit();
        return ((Number) spinner.getValue()).doubleValue();
    }

    /**
     * Asigna un valor entero al spinner ajustándolo al rango de su modelo.
     *
     * @param spinner spinner numérico
     * @param valor   valor deseado
     */
    private static void fijar(JSpinner spinner, int valor) {
        SpinnerNumberModel modelo = (SpinnerNumberModel) spinner.getModel();
        int minimo = ((Number) modelo.getMinimum()).intValue();
        int maximo = ((Number) modelo.getMaximum()).intValue();
        spinner.setValue(Math.max(minimo, Math.min(maximo, valor)));
    }

    /**
     * Asigna un valor decimal al spinner ajustándolo al rango de su modelo.
     *
     * @param spinner spinner numérico
     * @param valor   valor deseado
     */
    private static void fijar(JSpinner spinner, double valor) {
        SpinnerNumberModel modelo = (SpinnerNumberModel) spinner.getModel();
        double minimo = ((Number) modelo.getMinimum()).doubleValue();
        double maximo = ((Number) modelo.getMaximum()).doubleValue();
        spinner.setValue(Math.max(minimo, Math.min(maximo, valor)));
    }

